void setup() {
  Serial.begin(115200);

  // Initialize OLED display
  if (!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
    Serial.println(F("SSD1306 allocation failed"));
    for (;;);
  }

  // Set up button pins
  pinMode(BUTTON_NEXT, INPUT_PULLUP);
  pinMode(BUTTON_SELECT, INPUT_PULLUP);

  showMenu(selectedIndex);  // Show menu at startup
}

// Loop Function
void loop() {
  handleMenuNavigation();
  
  // Handle the captive portal if Fake AP is active
  if (WiFi.softAPgetStationNum() > 0) {
    dnsServer.processNextRequest();
    webServer.handleClient();
  }
}

// Function to display the main menu
void showMenu(uint8_t selectedIndex) {
  display.clearDisplay();
  display.setTextSize(1);
  display.setTextColor(SSD1306_WHITE);

  const char* menuOptions[5] = { "WiFi", "Radio", "RFID", "Remote", "Setting" };

  for (uint8_t i = 0; i < 5; i++) {
    if (i == selectedIndex) {
      display.setTextColor(SSD1306_BLACK, SSD1306_WHITE); // Highlighted item
    } else {
      display.setTextColor(SSD1306_WHITE);
    }

    display.setCursor(10, 10 + (i * 10));
    display.println(menuOptions[i]);
  }

  display.display();
}

// Function to handle menu navigation with a single button
void handleMenuNavigation() {
  static uint8_t lastStateNext = HIGH;
  static uint8_t lastStateSelect = HIGH;

  uint8_t currentStateNext = digitalRead(BUTTON_NEXT);  // Scroll button (D5)
  uint8_t currentStateSelect = digitalRead(BUTTON_SELECT);

  if (currentStateNext == LOW && lastStateNext == HIGH) {
    if (inSettings) {
      // In settings screen, go to next option or back if on "Back"
      settingIndex = (settingIndex + 1) % 4; // 4 options now (3 settings + "Back")
      showSettings();  // Update the settings screen
    } else if (inWiFiMenu) {
      // In WiFi menu, go to next option or back if on "Back"
      wifiIndex = (wifiIndex + 1) % 4; // 4 options now (Fake AP, Evil Twin, Back)
      showWiFiMenu(); // Update the WiFi menu screen
    } else {
      selectedIndex = (selectedIndex + 1) % 5; // Loop through menu options
      showMenu(selectedIndex); // Update the menu display
    }
    delay(200); // Debounce delay
  }

  if (currentStateSelect == LOW && lastStateSelect == HIGH) {
    Serial.print("Selected: ");
    if (inSettings) {
      // If in settings, go back to the menu if "Back" is selected
      if (settingIndex == 3) {
        inSettings = false;  // Go back to the main menu
        showMenu(selectedIndex);
      } else {
        Serial.print("Settings Option: ");
        Serial.println(settingIndex);
      }
    } else if (inWiFiMenu) {
      // Handle WiFi menu selection
      switch (wifiIndex) {
        case 0: 
          Serial.println("Fake AP selected");
          startFakeAP();  // Start the Fake AP
          break;
        case 1: 
          Serial.println("Evil Twin selected"); 
          break;
        case 2: // Back option
          inWiFiMenu = false;
          showMenu(selectedIndex);  // Go back to main menu
          break;
      }
    } else {
      switch (selectedIndex) {
        case 0:
          inWiFiMenu = true;  // Show WiFi menu
          showWiFiMenu();
          break;
        case 1: Serial.println("Radio"); break;
        case 2: Serial.println("RFID"); break;
        case 3: Serial.println("Remote"); break;
        case 4:
          inSettings = true;  // Show settings menu
          showSettings();
          break;
      }
    }
    delay(200); // Debounce delay
  }

  lastStateNext = currentStateNext;
  lastStateSelect = currentStateSelect;
}

// Function to display the Settings screen
void showSettings() {
  display.clearDisplay();
  display.setTextSize(1);
  display.setTextColor(SSD1306_WHITE);

  display.setCursor(10, 10);
  display.println("Settings");

  const char* settingOptions[4] = { "Option 1", "Option 2", "Option 3", "Back" };

  // Loop through the settings options and display them
  for (uint8_t i = 0; i < 4; i++) {
    if (i == settingIndex) {
      display.setTextColor(SSD1306_BLACK, SSD1306_WHITE); // Highlighted item
    } else {
      display.setTextColor(SSD1306_WHITE);
    }

    display.setCursor(10, 20 + (i * 10));
    display.println(settingOptions[i]);
  }

  display.display();
}

// Function to display the WiFi menu
